#
#      Name :      cp437font8.py
#      Author :    bmarty <bmarty@mailo.com>
#      Purpose :   T-131 : font_cp437_8x8.h, the 256 glyphs of code page 437 in 8 x 8 (MSB = left pixel,
#                  8 bytes per glyph) for the colour text mode 3, and the Latin-1 -> CP437 table of the
#                  console (its $A0-$FF are Latin-1, as NeoDOS and NeoBASIC send them).
#                  Source : the Linux console font Uni2-VGA8.psf.gz (console-setup : "All console fonts
#                  are public domain by nature"), glyphs found by their CP437 Unicode code point. The 7
#                  it lacks (10 11 9E A9 EC EF F0) are drawn below, in the IBM CGA style.
#      Usage :     python3 cp437font8.py [Uni2-VGA8.psf.gz] [../include/interface/font_cp437_8x8.h]
#
# ***************************************************************************************
import gzip, sys

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Uni2-VGA8.psf.gz"
dst = sys.argv[2] if len(sys.argv) > 2 else "../include/interface/font_cp437_8x8.h"
data = gzip.open(src).read()
assert data[0:2] == b"\x36\x04" and data[3] == 8, "PSF1 8 lignes attendu"
count = 512 if data[2] & 1 else 256
glyphs = [data[4 + i * 8:4 + (i + 1) * 8] for i in range(count)]
table, uni, g, i = data[4 + count * 8:], {}, 0, 0
while g < count and i + 1 < len(table):
    v = table[i] | table[i + 1] << 8
    i += 2
    if v == 0xFFFF: g += 1; continue
    if v == 0xFFFE: continue
    uni.setdefault(v, g)

LOW = "☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"
def unicode_of(c):
    if c == 0: return 0x20
    if c < 32: return ord(LOW[c - 1])
    if c == 0x7F: return ord("⌂")
    return ord(bytes([c]).decode("cp437"))

DRAWN = {0x10: [0x80, 0xE0, 0xF8, 0xFE, 0xF8, 0xE0, 0x80, 0x00],		# ►
         0x11: [0x02, 0x0E, 0x3E, 0xFE, 0x3E, 0x0E, 0x02, 0x00],		# ◄
         0x9E: [0xF8, 0xCC, 0xCC, 0xFA, 0xC6, 0xCF, 0xC6, 0xC7],		# ₧
         0xA9: [0x00, 0x00, 0x00, 0xFC, 0xC0, 0xC0, 0x00, 0x00],		# ⌐
         0xEC: [0x00, 0x00, 0x7E, 0xDB, 0xDB, 0x7E, 0x00, 0x00],		# ∞
         0xEF: [0x78, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0x00],		# ∩
         0xF0: [0x00, 0xFC, 0x00, 0x00, 0xFC, 0x00, 0xFC, 0x00]}		# ≡
font, drawn = [], []
for c in range(256):
    u = unicode_of(c)
    if u in uni: font.append(list(glyphs[uni[u]]))
    else:
        assert c in DRAWN, "glyphe %02X absent de la source et non dessiné" % c
        font.append(DRAWN[c]); drawn.append(c)

import unicodedata
l1 = []																	# Latin-1 $A0-$FF -> CP437 : the same character,
for c in range(0xA0, 0x100):											# else its letter without accent (À -> A), else '?'
    ch = bytes([c]).decode("latin-1")
    if ch in "¶§\u00ad": l1.append({"¶": 0x14, "§": 0x15, "\u00ad": ord("-")}[ch]);continue	# CP437 glyphs 14, 15
    try: l1.append(ch.encode("cp437")[0])
    except UnicodeEncodeError:
        base = unicodedata.normalize("NFD", ch)[0]
        l1.append(base.encode("cp437")[0] if base.isascii() and base.isprintable() else ord("?"))

out = ["// Generated by firmware/common/scripts/cp437font8.py (T-131) : do not edit.",
       "// Code page 437, 256 glyphs 8 x 8, 8 bytes per glyph, MSB = left pixel. Source : Uni2-VGA8.psf.gz",
       "// (console-setup, public domain) ; drawn here (IBM CGA style) : " + " ".join("%02X" % c for c in drawn) + ".",
       "#ifndef _FONT_CP437_8X8_H", "#define _FONT_CP437_8X8_H",
       "static const uint8_t fontCP437_8x8[256 * 8] = {"]
for c in range(256):
    out.append("\t" + ",".join("0x%02x" % b for b in font[c]) + ",\t// %02X" % c)
out += ["};", "// Latin-1 $A0-$FF (console codes) -> CP437 : same character, else the letter without accent, else '?'",
        "static const uint8_t latin1ToCP437[96] = {"]
for k in range(0, 96, 16):
    out.append("\t" + ",".join("0x%02x" % b for b in l1[k:k + 16]) + ",")
out += ["};", "#endif"]
open(dst, "w").write("\n".join(out) + "\n")
print("%s : 256 glyphes (dessinés : %s), Latin-1 en « ? » : %s" % (dst, " ".join("%02X" % c for c in drawn), " ".join("%02X" % (k + 0xA0) for k, v in enumerate(l1) if v == ord("?"))))
